"""Generates TypeScript types and Pydantic v2 models from contracts/*.schema.json.

Run through scripts/contracts.sh. Handles the subset of JSON Schema the contracts use.
"""

import json
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
TS_DIR = Path("worker/src/contracts")
PY_DIR = Path("node/src/yt_digest_node/contracts")
EVENT_ENUM = "LogEventName"


def header(comment: str, schema_file: str | None) -> str:
    source = f"from {schema_file}" if schema_file else "from contracts/"
    return f"{comment} Generated by scripts/contracts.sh {source}. Do not edit.\n"


def literal(values: list[Any]) -> str:
    return ", ".join(json.dumps(v) if v is not None else "None" for v in values)


def py_type(schema: dict[str, Any], uses: set[str]) -> tuple[str, list[str]]:
    """Returns the annotation and the Field(...) arguments of a property schema."""
    args: list[str] = []
    types = schema.get("type", [])
    types = types if isinstance(types, list) else [types]
    nullable = "null" in types
    if "enum" in schema:
        values = [v for v in schema["enum"] if v is not None]
        nullable = nullable or None in schema["enum"]
        uses.add("Literal")
        base = f"Literal[{literal(values)}]"
    else:
        kind = next(t for t in types if t != "null")
        if kind == "string":
            base = "str"
        elif kind == "integer":
            base = "int"
        elif kind == "number":
            base = "float"
        elif kind == "boolean":
            base = "bool"
        elif kind == "array":
            item, _ = py_type(schema["items"], uses)
            base = f"list[{item}]"
        else:
            base = "dict[str, object]"
    if "pattern" in schema:
        args.append(f'pattern=r"{schema["pattern"]}"')
    if "minimum" in schema:
        args.append(f"ge={schema['minimum']}")
    if "maximum" in schema:
        args.append(f"le={schema['maximum']}")
    return (f"{base} | None" if nullable else base), args


def gen_python(schema: dict[str, Any], schema_file: str) -> str:
    uses: set[str] = set()
    required = set(schema["required"])
    fields: list[str] = []
    for name, prop in schema["properties"].items():
        if name == "event":
            annotation, args = EVENT_ENUM, list[str]()
            uses.add("StrEnum")
        else:
            annotation, args = py_type(prop, uses)
        if name not in required:
            annotation += " | None"
            args.insert(0, "default=None")
        if args:
            uses.add("Field")
            line = f"    {name}: {annotation} = Field({', '.join(args)})"
            if len(line) > 88:  # the layout `ruff format` gives a single long argument
                line = f"    {name}: {annotation} = Field(\n        {', '.join(args)}\n    )"
        else:
            line = f"    {name}: {annotation}"
        fields.append(line)
    out = header("#", schema_file) + "\n"
    if "StrEnum" in uses:
        out += "from enum import StrEnum\n"
    if "Literal" in uses:
        out += "from typing import Literal\n"
    if "StrEnum" in uses or "Literal" in uses:
        out += "\n"
    out += "from pydantic import BaseModel, ConfigDict"
    out += ", Field\n\n\n" if "Field" in uses else "\n\n\n"
    if "StrEnum" in uses:
        out += f"class {EVENT_ENUM}(StrEnum):\n"
        for value in schema["properties"]["event"]["enum"]:
            member = value.replace(".", "_").upper()
            out += f'    {member} = "{value}"\n'
        out += "\n\n"
    out += f"class {schema['title']}(BaseModel):\n"
    out += '    model_config = ConfigDict(extra="forbid", strict=True)\n\n'
    out += "\n".join(fields) + "\n"
    return out


def ts_type(schema: dict[str, Any]) -> str:
    types = schema.get("type", [])
    types = types if isinstance(types, list) else [types]
    nullable = "null" in types
    if "enum" in schema:
        nullable = nullable or None in schema["enum"]
        base = " | ".join(json.dumps(v) for v in schema["enum"] if v is not None)
    else:
        kind = next(t for t in types if t != "null")
        if kind == "string":
            base = "string"
        elif kind in ("integer", "number"):
            base = "number"
        elif kind == "boolean":
            base = "boolean"
        elif kind == "array":
            item = ts_type(schema["items"])
            base = f"({item})[]" if " " in item else f"{item}[]"
        else:
            base = "Record<string, unknown>"
    return f"{base} | null" if nullable else base


def gen_typescript(schema: dict[str, Any], schema_file: str) -> str:
    required = set(schema["required"])
    out = header("//", schema_file) + "\n"
    if "event" in schema["properties"]:
        names = ",\n".join(
            f"  {json.dumps(v)}" for v in schema["properties"]["event"]["enum"]
        )
        out += f"export const LOG_EVENT_NAMES = [\n{names},\n] as const;\n\n"
        out += f"export type {EVENT_ENUM} = (typeof LOG_EVENT_NAMES)[number];\n\n"
    out += f"export interface {schema['title']} {{\n"
    for name, prop in schema["properties"].items():
        optional = "" if name in required else "?"
        annotation = EVENT_ENUM if name == "event" else ts_type(prop)
        out += f"  {name}{optional}: {annotation};\n"
    out += "}\n"
    return out


def generate() -> dict[str, str]:
    """Returns the content of every generated file, by path relative to the repository."""
    files: dict[str, str] = {}
    schemas = sorted((ROOT / "contracts").glob("*.schema.json"))
    for path in schemas:
        schema = json.loads(path.read_text())
        stem = path.name.removesuffix(".schema.json")
        files[str(TS_DIR / f"{stem}.ts")] = gen_typescript(schema, path.name)
        files[str(PY_DIR / f"{stem.replace('-', '_')}.py")] = gen_python(
            schema, path.name
        )
    files[str(PY_DIR / "__init__.py")] = header("#", None)
    return files


def main(argv: list[str]) -> int:
    if argv not in ([], ["--check"]):
        print("usage: contracts.sh [--check]", file=sys.stderr)
        return 2
    files = generate()
    if not argv:
        for directory in (TS_DIR, PY_DIR):
            for old in (ROOT / directory).glob("*"):
                old.unlink()
        for rel, text in files.items():
            target = ROOT / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        for rel, text in files.items():
            target = Path(tmp) / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
        stale: list[str] = []
        committed = {
            str(p.relative_to(ROOT))
            for d in (TS_DIR, PY_DIR)
            for p in (ROOT / d).glob("*")
            if p.is_file()
        }
        for rel in sorted(committed | set(files)):
            current, wanted = ROOT / rel, Path(tmp) / rel
            if (
                not current.exists()
                or not wanted.exists()
                or current.read_text() != wanted.read_text()
            ):
                stale.append(rel)
    for rel in stale:
        print(f"stale generated file: {rel}", file=sys.stderr)
    if stale:
        print("run ./scripts/contracts.sh to regenerate", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
